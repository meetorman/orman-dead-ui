#!/usr/bin/env node
// The contract gate: composed API output must satisfy the TS contracts.
// Emits live payloads via orman_dead.parity, generates a throwaway `satisfies`
// check file (the same mechanism the fixture gate used), and typechecks it.
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = dirname(dirname(fileURLToPath(import.meta.url)));
const folioDir = join(webDir, 'packages', 'folio');
const outDir = join(folioDir, '.contracts-out');

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

execFileSync('python3', ['-m', 'orman_dead.parity', 'emit', '--out', outDir], {
  cwd: '/home/ring/orman-dead-api',
  stdio: 'inherit',
});

const checkFile = join(outDir, 'contracts-live.check.ts');
writeFileSync(
  checkFile,
  `// GENERATED by tools/check-contracts.mjs — composed API output vs contracts.
import show from './shows/1977-05-08.json';
import venue from './venues/barton-hall.json';
import venues from './venues.json';
import site from './site.json';
import type { ShowRecord } from '../src/contracts/show';
import type { SiteChrome } from '../src/contracts/site';
import type { VenueRecord } from '../src/contracts/venue';
import type { VenuesIndex } from '../src/contracts/venues';

show satisfies ShowRecord;
venue satisfies VenueRecord;
venues satisfies VenuesIndex;
site satisfies SiteChrome;
`,
);

execFileSync(
  join(webDir, 'node_modules', '.bin', 'tsc'),
  [
    '--noEmit',
    '--strict',
    '--target',
    'es2022',
    '--module',
    'esnext',
    '--moduleResolution',
    'bundler',
    '--resolveJsonModule',
    '--jsx',
    'react-jsx',
    checkFile,
  ],
  { cwd: folioDir, stdio: 'inherit' },
);
console.log('[contracts] composed API output satisfies the TS contracts');
